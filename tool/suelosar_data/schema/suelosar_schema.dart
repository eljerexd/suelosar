/// The SuelosAR soil-polygon attribute schema — the single place the data
/// pipeline defines the target fields a province's GIS must be mapped to.
///
/// The same list is still written, independently, in `docker/build_map.sh`,
/// `docker/validate_map.py`, `tool/optimize_buenos_aires_pmtiles.dart`
/// (`keptAttributes`) and read by `lib/gis/gis_map_screen.dart`. Fase 1 does
/// not touch those; `test/tool/suelosar_data/schema_consistency_test.dart`
/// fails if they drift apart.
abstract final class SuelosArSchema {
  /// Maximum number of soil-series components per mapping unit.
  static const seriesSlots = 6;

  /// Per-unit descriptive fields.
  static const unitFields = [
    'SIMBC',
    'Nombre_UC',
    'TIPO',
    'CAP_USO',
    'PAISAJE',
  ];

  static final seriesFields = [
    for (var n = 1; n <= seriesSlots; n++) 'SERIE$n',
  ];

  static final percentageFields = [
    for (var n = 1; n <= seriesSlots; n++) 'PORC$n',
  ];

  /// Every field the Docker pipeline requires as a column (17).
  static final requiredFields = [
    ...unitFields,
    ...seriesFields,
    ...percentageFields,
  ];

  /// Fields a province may map but the pipeline does not require —
  /// `OBJECTID` is generated by Tippecanoe when absent. `SERIE7`/`SERIE8`
  /// (Parte 12B): some provinces' own GIS source declares more than
  /// [seriesSlots] components per map unit (Córdoba's `carta_suelo_
  /// 100mil_2025` goes up to `serie_8`) with no matching percentage field
  /// to go with the extra slots — deliberately optional, not part of
  /// [seriesFields]/[requiredFields]/[percentageFields], so every other
  /// province (whose mapping only ever declares up to `SERIE6`) is
  /// completely unaffected: no new required column, no Docker/PMTiles
  /// schema change for them. A province that does map `SERIE7`/`SERIE8`
  /// lists them in `gis.series.extra_fields` so the pipeline's own
  /// series-detection/crossref counts them too (see
  /// `SeriesConfig.extraSeriesFields`) — otherwise they'd reach the
  /// normalized GeoJSON but be invisible to the catalog cross-reference.
  /// `SUBGRUPO1..5`/`POSICION1..5`/`IP` (Parte 20): Córdoba's
  /// `carta_suelo_500mil_2024` classifies map units by soil taxonomy
  /// (subgroup + landscape position, e.g. "Haplustol típico" /
  /// "Pendientes pronunciadas") instead of named series — there is no
  /// `nombre`/`serie_N` in that source at all. These are deliberately a
  /// separate set of optional fields, not aliases of [seriesFields]/
  /// [percentageFields]: mixing taxonomic subgroups into `SERIE1-8` would
  /// make the catalog cross-reference (which expects `SERIEn` to hold a
  /// documented series name) treat a generic soil-taxonomy term as a
  /// series, which it is not. No other province maps these.
  static const optionalFields = [
    'OBJECTID',
    'SERIE7',
    'SERIE8',
    'SUBGRUPO1',
    'SUBGRUPO2',
    'SUBGRUPO3',
    'SUBGRUPO4',
    'SUBGRUPO5',
    'POSICION1',
    'POSICION2',
    'POSICION3',
    'POSICION4',
    'POSICION5',
    'IP',
  ];

  /// Every attribute the app reads from a feature (18).
  static final appAttributes = {...requiredFields, ...optionalFields};

  /// Fields whose coverage is held to the province's thresholds by default.
  /// The other series slots are legitimately sparse (most units have fewer
  /// than six components), so their coverage is only reported.
  static final defaultThresholdFields = [
    'SIMBC',
    'Nombre_UC',
    'TIPO',
    'CAP_USO',
    'PAISAJE',
    'SERIE1',
    'PORC1',
  ];

  static bool isPercentage(String field) => percentageFields.contains(field);

  static bool isKnown(String field) =>
      requiredFields.contains(field) || optionalFields.contains(field);
}
